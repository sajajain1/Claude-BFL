package com.modernizeai.ai;

import com.modernizeai.config.ModernizeAiProperties;
import com.modernizeai.exception.AiUnavailableException;
import com.modernizeai.exception.ApiException;
import com.modernizeai.model.AiExplanation;
import com.modernizeai.model.AiStatus;
import com.modernizeai.model.AnalysisReport;
import com.modernizeai.model.ExplanationResponse;
import com.modernizeai.model.Finding;
import com.modernizeai.service.AnalysisStore;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;
import java.util.stream.Collectors;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;

/** Generates, validates and caches Claude explanations for selected findings. */
@Service
public class AiExplanationService {

    private static final Logger log = LoggerFactory.getLogger(AiExplanationService.class);
    public static final String NOTICE = "Generated by Claude from limited snippets. AI output can be wrong or incomplete; "
            + "verify every suggestion against your code and tests before applying it.";

    private final LlmClient llm;
    private final ExplanationPromptBuilder promptBuilder;
    private final AiResponseParser parser;
    private final AnalysisStore store;
    private final ModernizeAiProperties.Ai config;

    public AiExplanationService(LlmClient llm, ExplanationPromptBuilder promptBuilder, AiResponseParser parser, AnalysisStore store,
                                ModernizeAiProperties properties) {
        this.llm = llm;
        this.promptBuilder = promptBuilder;
        this.parser = parser;
        this.store = store;
        this.config = properties.ai();
    }

    public AiStatus status() {
        return llm.isConfigured()
                ? new AiStatus(true, llm.modelName(), "Claude explanations are enabled.")
                : new AiStatus(false, llm.modelName(), "AI explanations are disabled because ANTHROPIC_API_KEY is not set. "
                        + "The deterministic scanner works fully without it.");
    }

    public ExplanationResponse explain(String analysisId, List<String> requestedIds) {
        AnalysisReport report = store.get(analysisId);
        Set<String> ids = new LinkedHashSet<>(requestedIds);
        if (ids.size() > config.maxFindingsPerRequest()) {
            throw new ApiException(HttpStatus.BAD_REQUEST, "VALIDATION_FAILED",
                    "At most " + config.maxFindingsPerRequest() + " findings can be explained per request.");
        }
        Map<String, Finding> byId = report.findings().stream().collect(Collectors.toMap(Finding::id, Function.identity()));
        List<String> unknown = ids.stream().filter(id -> !byId.containsKey(id)).toList();
        if (!unknown.isEmpty()) {
            throw new ApiException(HttpStatus.BAD_REQUEST, "UNKNOWN_FINDING", "Unknown finding id(s): " + String.join(", ", unknown));
        }
        if (!llm.isConfigured()) {
            throw new AiUnavailableException("AI_NOT_CONFIGURED", "AI explanations require an Anthropic API key. "
                    + "Set ANTHROPIC_API_KEY and restart the backend. All deterministic findings remain available.");
        }

        Map<String, AiExplanation> cache = store.explanations(analysisId);
        List<Finding> toAsk = ids.stream().filter(id -> !cache.containsKey(id)).map(byId::get).toList();
        String model = llm.modelName();
        if (!toAsk.isEmpty()) {
            String prompt = promptBuilder.userPrompt(report, toAsk, config.maxSnippetChars());
            LlmClient.LlmResult result = llm.complete(ExplanationPromptBuilder.SYSTEM_PROMPT, prompt, ExplanationSchema.schema());
            Set<String> expected = toAsk.stream().map(Finding::id).collect(Collectors.toCollection(LinkedHashSet::new));
            List<AiExplanation> parsed = parser.parse(result.text(), expected);
            parsed.forEach(e -> cache.put(e.findingId(), e));
            model = result.model();
            log.info("AI explanations generated analysisId={} count={} model={}", analysisId, parsed.size(), model);
        }
        List<AiExplanation> out = new ArrayList<>();
        for (String id : ids) out.add(cache.get(id));
        return new ExplanationResponse(analysisId, model, out, NOTICE);
    }

    public Map<String, AiExplanation> cached(String analysisId) {
        return Map.copyOf(store.explanations(analysisId));
    }
}
